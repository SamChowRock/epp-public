BEGIN;
SET LOCAL lock_timeout = '2s';

ALTER TABLE public.users ADD COLUMN nickname text,
  ADD COLUMN nickname_visible boolean NOT NULL DEFAULT false,
  ADD CONSTRAINT users_nickname_size CHECK (octet_length(nickname) BETWEEN 1 AND 192);

CREATE TABLE public.nickname_changes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  changed_at timestamptz(3) NOT NULL
);
CREATE INDEX nickname_changes_owner_time_idx ON public.nickname_changes(user_id, changed_at);
COMMIT;
